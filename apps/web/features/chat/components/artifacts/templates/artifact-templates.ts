export function fillTemplate(content: string): string {
  return content.replace(/\{\{date\}\}/g, today());
}

export function templatesOfKind(
  kind: TemplateKind,
  extra: readonly ArtifactTemplate[] = [],
): ArtifactTemplate[] {
  return [...BUILT_IN_TEMPLATES, ...extra].filter((template) => template.kind === kind);
}
