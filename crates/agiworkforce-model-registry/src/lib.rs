//! Typed Rust access to AGI Workforce's canonical model registry.
//!
//! Model identity, capabilities, routes, harness status, and Auto policy are
//! generated from `packages/ai/model-registry`. Rust applications consume this
//! crate instead of maintaining provider/model tables or token-threshold
//! routing rules of their own.

use std::collections::{HashMap, HashSet};
use std::sync::OnceLock;

use serde::{Deserialize, Serialize};
use thiserror::Error;

#[path = "generated/model_registry.rs"]
mod generated;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum TrustMode {
    Local,
    OnDevice,
    Byok,
    ManagedCloud,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum RoutingProfile {
    Economy,
    Balanced,
    Premium,
}

impl RoutingProfile {
    fn as_key(self) -> &'static str {
        match self {
            Self::Economy => "economy",
            Self::Balanced => "balanced",
            Self::Premium => "premium",
        }
    }
}

