#[derive(Debug, Clone)]
pub struct AutoRoutingRequest<'a> {
    pub selection: Option<&'a str>,
    pub task_type: RoutingTaskType,
    pub subscription_tier: Option<&'a str>,
    pub trust_mode: TrustMode,
    pub current_model_key: Option<&'a str>,
    pub previous_task_type: Option<RoutingTaskType>,
    pub required_capabilities: &'a [IntrinsicCapability],
    /// Runtime-specific harness adapters that the caller can actually execute.
    /// `None` means the caller accepts every registry-declared harness.
    pub allowed_harnesses: Option<&'a [&'a str]>,
    /// Canonical surface/mode admission profile generated by the registry.
    pub runtime_profile_id: Option<&'a str>,
    pub us_only: bool,
    pub estimated_input_tokens: Option<u64>,
    pub estimated_output_tokens: Option<u64>,
}

impl Default for AutoRoutingRequest<'_> {
    fn default() -> Self {
        Self {
            selection: None,
            task_type: RoutingTaskType::General,
            subscription_tier: None,
            // Fail closed when a caller forgets to declare its trust boundary.
            trust_mode: TrustMode::Local,
            current_model_key: None,
            previous_task_type: None,
            required_capabilities: &[],
            allowed_harnesses: None,
            runtime_profile_id: None,
            us_only: false,
            estimated_input_tokens: None,
            estimated_output_tokens: None,
        }
    }
}

